CREATE SCHEMA IF NOT EXISTS warehouse;

-- Rebuild dimensions.
-- Run this script before creating fact tables.
DROP TABLE IF EXISTS warehouse.dim_customer;
DROP TABLE IF EXISTS warehouse.dim_product;
DROP TABLE IF EXISTS warehouse.dim_seller;
DROP TABLE IF EXISTS warehouse.dim_date;


-- ============================================================
-- 1. Date Dimension
-- Grain: One row per calendar date.
-- ============================================================

CREATE TABLE warehouse.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day_of_week SMALLINT NOT NULL,
    day_name VARCHAR(10) NOT NULL,
    day_of_month SMALLINT NOT NULL,
    week_of_year SMALLINT NOT NULL,
    month_number SMALLINT NOT NULL,
    month_name VARCHAR(10) NOT NULL,
    quarter_number SMALLINT NOT NULL,
    year_number SMALLINT NOT NULL,
    is_weekend BOOLEAN NOT NULL
);

WITH all_dates AS (
    SELECT purchase_timestamp::DATE AS calendar_date
    FROM transform.orders_clean

    UNION ALL

    SELECT approved_timestamp::DATE
    FROM transform.orders_clean

    UNION ALL

    SELECT carrier_timestamp::DATE
    FROM transform.orders_clean

    UNION ALL

    SELECT delivered_timestamp::DATE
    FROM transform.orders_clean

    UNION ALL

    SELECT estimated_delivery_timestamp::DATE
    FROM transform.orders_clean

    UNION ALL

    SELECT shipping_limit_timestamp::DATE
    FROM transform.order_items_clean
),

date_bounds AS (
    SELECT
        MIN(calendar_date) AS min_date,
        MAX(calendar_date) AS max_date
    FROM all_dates
    WHERE calendar_date IS NOT NULL
),

calendar AS (
    SELECT
        generated_date::DATE AS full_date
    FROM date_bounds
    CROSS JOIN LATERAL generate_series(
        min_date::TIMESTAMP,
        max_date::TIMESTAMP,
        INTERVAL '1 day'
    ) AS gs(generated_date)
)

INSERT INTO warehouse.dim_date (
    date_key,
    full_date,
    day_of_week,
    day_name,
    day_of_month,
    week_of_year,
    month_number,
    month_name,
    quarter_number,
    year_number,
    is_weekend
)
SELECT
    TO_CHAR(full_date, 'YYYYMMDD')::INTEGER AS date_key,
    full_date,
    EXTRACT(ISODOW FROM full_date)::SMALLINT,
    TO_CHAR(full_date, 'FMDay'),
    EXTRACT(DAY FROM full_date)::SMALLINT,
    EXTRACT(WEEK FROM full_date)::SMALLINT,
    EXTRACT(MONTH FROM full_date)::SMALLINT,
    TO_CHAR(full_date, 'FMMonth'),
    EXTRACT(QUARTER FROM full_date)::SMALLINT,
    EXTRACT(YEAR FROM full_date)::SMALLINT,
    EXTRACT(ISODOW FROM full_date) IN (6, 7)
FROM calendar;


-- ============================================================
-- 2. Customer Dimension
-- Grain: One row per customer_id.
-- customer_unique_id is retained for repeat-customer analysis.
-- ============================================================

CREATE TABLE warehouse.dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(40) NOT NULL UNIQUE,
    customer_unique_id VARCHAR(40),
    customer_zip_code_prefix VARCHAR(10),
    customer_city VARCHAR(100),
    customer_state VARCHAR(10)
);

INSERT INTO warehouse.dim_customer (
    customer_id,
    customer_unique_id,
    customer_zip_code_prefix,
    customer_city,
    customer_state
)
SELECT
    customer_id,
    customer_unique_id,
    customer_zip_code_prefix,
    customer_city,
    customer_state
FROM transform.customers_clean;


-- ============================================================
-- 3. Product Dimension
-- Grain: One row per product_id.
-- English category comes from the source translation lookup.
-- ============================================================

CREATE TABLE warehouse.dim_product (
    product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(40) NOT NULL UNIQUE,
    product_category_name VARCHAR(150),
    product_category_name_english VARCHAR(150) NOT NULL,
    category_status VARCHAR(50) NOT NULL,
    product_name_length INTEGER,
    product_description_length INTEGER,
    product_photos_qty INTEGER,
    product_weight_g INTEGER,
    product_length_cm INTEGER,
    product_height_cm INTEGER,
    product_width_cm INTEGER
);


INSERT INTO warehouse.dim_product (
    product_id,
    product_category_name,
    product_category_name_english,
    category_status,
    product_name_length,
    product_description_length,
    product_photos_qty,
    product_weight_g,
    product_length_cm,
    product_height_cm,
    product_width_cm
)
SELECT
    p.product_id,
    p.product_category_name,

    CASE
        WHEN p.product_category_name =
            'portateis_cozinha_e_preparadores_de_alimentos'
            THEN 'Portable Kitchen and Food Preparers'

        WHEN p.product_category_name = 'pc_gamer'
            THEN 'Gaming PC'

        ELSE COALESCE(
            NULLIF(BTRIM(t.product_category_name_english), ''),
            'Unknown'
        )
    END AS product_category_name_english,

    CASE
        WHEN p.is_missing_category
            THEN 'Missing source category'

        WHEN t.product_category_name IS NULL
             AND p.product_category_name NOT IN (
                'portateis_cozinha_e_preparadores_de_alimentos',
                'pc_gamer'
             )
            THEN 'No translation match'

        ELSE 'Translation available'
    END AS category_status,

    p.product_name_length,
    p.product_description_length,
    p.product_photos_qty,
    p.product_weight_g,
    p.product_length_cm,
    p.product_height_cm,
    p.product_width_cm

FROM transform.products_clean p

LEFT JOIN staging.product_category_translation_raw t
    ON p.product_category_name =
       NULLIF(BTRIM(t.product_category_name), '');



-- ============================================================
-- 4. Seller Dimension
-- Grain: One row per seller_id.
-- ============================================================

CREATE TABLE warehouse.dim_seller (
    seller_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id VARCHAR(40) NOT NULL UNIQUE,
    seller_zip_code_prefix VARCHAR(10),
    seller_city VARCHAR(100),
    seller_state VARCHAR(10)
);

INSERT INTO warehouse.dim_seller (
    seller_id,
    seller_zip_code_prefix,
    seller_city,
    seller_state
)
SELECT
    seller_id,
    seller_zip_code_prefix,
    seller_city,
    seller_state
FROM transform.sellers_clean;


-- ============================================================
-- 5. Dimension Build Summary
-- ============================================================

SELECT 'dim_date' AS dimension_name, COUNT(*) AS row_count
FROM warehouse.dim_date

UNION ALL

SELECT 'dim_customer', COUNT(*)
FROM warehouse.dim_customer

UNION ALL

SELECT 'dim_product', COUNT(*)
FROM warehouse.dim_product

UNION ALL

SELECT 'dim_seller', COUNT(*)
FROM warehouse.dim_seller

ORDER BY dimension_name;